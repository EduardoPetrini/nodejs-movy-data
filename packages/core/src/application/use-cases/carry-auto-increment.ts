import { DatabaseType } from '../../domain/types/connection.types.js';
import { ColumnSchema, TableSchema } from '../../domain/types/schema.types.js';

/** A PostgreSQL sequence default: `nextval('users_id_seq'::regclass)`. */
const NEXTVAL_DEFAULT = /^\s*nextval\s*\(/i;

export interface CarriedTable {
  table: TableSchema;
  /** Columns that were auto-increment on the source and are plain on the destination. */
  dropped: string[];
}

/**
 * Settles which columns of a table crossing engines keep auto-increment.
 *
 * Each engine says "this column numbers itself" differently, and the source's
 * spelling is wrong on any other engine: a PG `serial` arrives as
 * `DEFAULT nextval('…')`, naming a sequence MySQL and MSSQL do not have, and
 * MySQL rejects it outright. So that default is dropped and the column's
 * `autoIncrement` flag carries the meaning instead, which each synchronizer
 * spells natively (AUTO_INCREMENT, IDENTITY, GENERATED BY DEFAULT AS IDENTITY).
 *
 * The destination's rules then decide which flags survive. MySQL allows one
 * auto column per table and it must lead a key, so only the first column of
 * the primary key may keep it; MSSQL allows one IDENTITY anywhere; PostgreSQL
 * allows any number. A dropped column keeps its copied values, it only stops
 * numbering new rows, so the caller reports it rather than failing the run.
 *
 * Same-engine Pairs return the table untouched: the source's spelling is
 * already the destination's.
 */
export function carryAutoIncrement(
  table: TableSchema,
  source: DatabaseType,
  dest: DatabaseType
): CarriedTable {
  if (source === dest) return { table, dropped: [] };

  const keeper = keeperFor(table, dest);
  const dropped: string[] = [];
  const columns = table.columns.map((col): ColumnSchema => {
    const defaultValue =
      dest !== DatabaseType.POSTGRES && col.defaultValue !== null && NEXTVAL_DEFAULT.test(col.defaultValue)
        ? null
        : col.defaultValue;
    if (!col.autoIncrement || keeper === undefined || keeper === col.name) {
      return { ...col, defaultValue };
    }
    dropped.push(col.name);
    return { ...col, defaultValue, autoIncrement: false };
  });

  return { table: { ...table, columns }, dropped };
}

/**
 * The one column allowed to stay auto-increment, `undefined` when every flagged
 * column may (PostgreSQL), or `null` when none may.
 */
function keeperFor(table: TableSchema, dest: DatabaseType): string | null | undefined {
  if (dest === DatabaseType.POSTGRES) return undefined;
  if (dest === DatabaseType.MYSQL) {
    const lead = table.constraints.find((c) => c.type === 'PRIMARY KEY')?.columns[0];
    const leadCol = table.columns.find((c) => c.name === lead);
    return leadCol?.autoIncrement ? leadCol.name : null;
  }
  return table.columns.find((c) => c.autoIncrement)?.name ?? null;
}
